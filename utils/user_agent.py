class UserAgentRotator:
    def __init__(self, agents: list[str] | None = None, custom: str | None = None):
        self._agents = list(agents or USER_AGENTS)
        self._custom = custom
        self._index = 0

    def get(self) -> str:
        if self._custom:
            return self._custom
        agent = self._agents[self._index % len(self._agents)]
        self._index += 1
        return agent

    def random(self) -> str:
        if self._custom:
            return self._custom
        return random.choice(self._agents)

    def add(self, agent: str) -> None:
        self._agents.append(agent)
